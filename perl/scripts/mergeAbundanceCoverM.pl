#!/usr/bin/env perl

use strict;
use warnings;

use Getopt::Long;
use Data::Dumper;

my $usage=<<'ENDHERE';
NAME:
mergeAbundance.pl

PURPOSE:
Merge multiple .cov files generated by CoverM to 
generate an abundance matrix.

INPUT:
--infiles <string> : bedtools .cov files, seperated by a ","
--min <int>        : will filter out genes or contigs having less than --min <int> total counts across all samples. 
                     Default = 1.

OUTPUT:
STDOUT <string>    : abundance matrix. Columns = samples/lib, Rows = genes or contigs.
--outfile_tpm      : abundance matrix in TPM.

NOTES:

BUGS/LIMITATIONS:
 
AUTHOR/SUPPORT:
Julien Tremblay - jtremblay514@gmail.com

ENDHERE

## OPTIONS
my ($help, $infiles, $type, $min, $outfile_tpm);
my $verbose = 0;

GetOptions(
   'infiles=s'     => \$infiles,
   'outfile_tpm=s' => \$outfile_tpm,
   'min=i'         => \$min,
   'verbose'       => \$verbose,
   'help'          => \$help
);
if ($help) { print $usage; exit; }

## MAIN
open(OUT, ">".$outfile_tpm)  or die "Can't open $outfile_tpm\n";

$min = 1 unless($min);
my @basenames;
my %hash;
my %hash_tpm;
my @infiles = split(/,/, $infiles);

for my $infile (@infiles){
    my $basename = $infile;
    $basename =~ s{.*/}{};         # removes path  
    $basename =~ s{\.[^.]+$}{};    # removes extension
    print STDERR "Processing $infile\n";
    push(@basenames, $basename);
    open(IN, "<".$infile) or die "Can't open $infile\n";

    while(<IN>){
        chomp;
        my @row = split(/\t/, $_);

        if(exists($hash{$row[0]})){
            $hash{$row[0]} = $hash{$row[0]}."\t".$row[1];
            $hash_tpm{$row[0]} = $hash_tpm{$row[0]}."\t".$row[2];
        }else{
            $hash{$row[0]} = $row[1];
            $hash_tpm{$row[0]} = $row[2];
        }
    }
    close(IN);
}

#print STDERR Dumper(\%hash_tpm);
#print STDERR join("\t", @basenames)."\n";

print STDOUT "feature_id\t".join("\t", @basenames)."\n";
for my $gene_id (keys %hash) {
    # here we could put a filter in gene abundance. Like say only keep genes having total counts >= 10.
    my @values = split(/\t/, $hash{$gene_id});
    my $total = eval join '+', @values;
    if($total >= $min){
        print STDOUT $gene_id."\t";
        print STDOUT $hash{$gene_id}."\n";
    }
}

print OUT "feature_id\t".join("\t", @basenames)."\n";
for my $gene_id (keys %hash_tpm) {
    my @values = split(/\t/, $hash_tpm{$gene_id});
    my $total = eval join '+', @values;
    if($total >= $min){
        print OUT $gene_id."\t";
        print OUT $hash_tpm{$gene_id}."\n";
    }
}

close(OUT);

exit;
